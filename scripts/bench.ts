/**
 * Grid benchmark: `pnpm bench` → docs/performance.md
 *
 * Starts the demo's Vite server, drives headless Chromium, and times the data grid at several sizes:
 * first render, scrolling (each step re-renders the visible window), and how many DOM rows exist.
 * Each number is the median of several runs. The figures depend on the machine; the file records it.
 */
import { createServer } from 'vite';
import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import os from 'node:os';

const RUNS = 5;
const median = (values: number[]) => [...values].sort((a, b) => a - b)[Math.floor(values.length / 2)];

const server = await createServer({ server: { port: 5199, strictPort: true }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH } : {});
const page = await browser.newPage();
// tsx wraps functions in a `__name` helper; the page that runs them doesn't have it
await page.addInitScript('window.__name = f => f;');
await page.goto('http://localhost:5199/');
await page.waitForSelector('nx-viewport');

type Result = { render: number; slowest: number; domRows: number };

/** One grid of `count` rows: time to render, mean time per scroll step, rows in the DOM. */
const measure = (count: number, virtual: boolean): Promise<Result> =>
  page.evaluate(async ({ count, virtual }) => {
    const entry = '/src/index.ts';
    const { NX } = await import(/* @vite-ignore */ entry);
    const data = Array.from({ length: count }, (_, i) => ({ id: i, name: `Row ${i}`, amount: i * 3.5, active: i % 2 === 0 }));
    const frame = () => new Promise(resolve => requestAnimationFrame(() => resolve(null)));

    const started = performance.now();
    const grid = NX.create({
      xtype: 'grid', data, height: 400, rowHeight: 40, virtual,
      columns: [{ field: 'id', header: 'Id', type: 'number' }, { field: 'name', header: 'Name' }, { field: 'amount', header: 'Amount', type: 'currency' }, { field: 'active', header: 'Active', type: 'boolean' }]
    });
    document.body.append(grid);
    await frame();
    await frame();
    const render = performance.now() - started;

    const body = grid.shadowRoot.querySelector('.nx-grid-body');
    const steps = 40;
    let slowest = 0;
    for (let i = 1; i <= steps; i++) {
      const t0 = performance.now();
      body.scrollTop = Math.floor((count * 40 * i) / steps / 1.01);
      body.dispatchEvent(new Event('scroll'));
      await frame(); // the grid redraws its window on the next frame
      await frame();
      slowest = Math.max(slowest, (performance.now() - t0) / 2);
    }
    const domRows = grid.shadowRoot.querySelectorAll('tbody tr:not(.spacer)').length;
    grid.remove();
    return { render, slowest, domRows };
  }, { count, virtual });

const cases: Array<{ rows: number; virtual: boolean }> = [
  { rows: 1_000, virtual: false },
  { rows: 5_000, virtual: false },
  { rows: 1_000, virtual: true },
  { rows: 10_000, virtual: true },
  { rows: 100_000, virtual: true },
  { rows: 1_000_000, virtual: true }
];

const lines: string[] = [];
for (const { rows, virtual } of cases) {
  const results: Result[] = [];
  for (let i = 0; i < RUNS; i++) results.push(await measure(rows, virtual));
  const row = {
    render: median(results.map(r => r.render)),
    slowest: median(results.map(r => r.slowest)),
    domRows: results[0].domRows
  };
  console.log(rows.toLocaleString('en-US'), virtual ? 'virtual' : 'plain', row);
  lines.push(`| ${rows.toLocaleString('en-US')} | ${virtual ? 'virtual' : 'all rows'} | ${row.render.toFixed(0)} ms | ${row.slowest.toFixed(1)} ms | ${row.domRows.toLocaleString('en-US')} |`);
}

const version = browser.version();
await browser.close();
await server.close();

await writeFile(
  new URL('../docs/performance.md', import.meta.url),
  `# Performance

Generated by \`pnpm bench\` (\`scripts/bench.ts\`); the numbers below are from one run and **depend on the machine**, so run it yourself before comparing anything.

It drives headless Chromium against the demo's dev server and times the data grid (4 columns, 40 px rows, a 400 px tall body). Each figure is the median of ${RUNS} runs.

| Rows | Mode | First render | Slowest frame while scrolling | Rows in the DOM |
| ---: | --- | ---: | ---: | ---: |
${lines.join('\n')}

- **First render**: from creating the grid to the second animation frame after it is in the page.
- **Slowest frame while scrolling**: 40 jumps across the whole data set, each redrawing the visible window; the slowest frame of the run. About 16.7 ms is 60 fps, so a figure near that means no frame was dropped.
- A virtual grid keeps the number of DOM rows constant, so its cost does not grow with the data; a plain grid renders every row.
- The data is already in memory, so this does not include fetching. A \`buffered\` store adds one request per page of rows in view.

Measured with ${version} on ${os.cpus().length} × ${os.cpus()[0]?.model.trim() ?? 'unknown CPU'}, ${os.platform()}, Node ${process.version}, against the Vite dev server (unminified code, so a production build is faster).
`
);
console.log('wrote docs/performance.md');
