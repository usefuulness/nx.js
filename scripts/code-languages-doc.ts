/**
 * Writes the table of languages into docs/editors.md, between the `languages:start` and `languages:end` markers,
 * from the registry itself, so the guide cannot drift from the code. `pnpm docs:languages`; a unit test fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listCodeLanguages } from '../src/core/code-languages';

export const START = '<!-- languages:start (generated by pnpm docs:languages) -->';
export const END = '<!-- languages:end -->';

export function languageTable(): string {
  const rows = listCodeLanguages().map(l => {
    const comment = l.comment ? [l.comment.line ? `\`${l.comment.line}\`` : '', l.comment.block ? `\`${l.comment.block[0]} ${l.comment.block[1]}\`` : ''].filter(Boolean).join(' · ') : '—';
    const names = l.aliases.join(', ') || '—';
    const files = [...l.extensions.map(e => `.${e}`), ...(l.filenames ?? [])].slice(0, 7).join(' ') || '—';
    return `| \`${l.id}\` | ${l.label} | ${names} | ${files} | ${comment} | ${l.rules?.length ? 'yes' : ''} | ${l.validate ? 'yes' : ''} |`;
  });
  return ['| Id | Name | Also called | Files | Comments | Colours | Checked |', '| --- | --- | --- | --- | --- | --- | --- |', ...rows].join('\n');
}

/** The guide with its table replaced by the current one. */
export function withLanguageTable(guide: string): string {
  const a = guide.indexOf(START);
  const b = guide.indexOf(END);
  if (a < 0 || b < a) throw new Error(`docs/editors.md needs the ${START} and ${END} markers`);
  return `${guide.slice(0, a)}${START}\n${languageTable()}\n${guide.slice(b)}`;
}

const file = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../docs/editors.md');
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(file, withLanguageTable(readFileSync(file, 'utf8')));
  console.log(`language table: ${listCodeLanguages().length} languages → docs/editors.md`);
}
