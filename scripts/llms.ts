/**
 * `llms.txt` and `llms-full.txt` for AI assistants (https://llmstxt.org): an index of the docs, and
 * every guide in one file. They are built from docs/*.md, so they never drift from the docs, and the
 * component reference inside is itself generated from the source (`pnpm docs:reference`).
 * `pnpm site` publishes them next to the docs.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';

export interface Guide {
  file: string;
  title: string;
  /** One line: what you learn there */
  summary: string;
}

/** The guides in reading order (docs/README.md lists the same ones). */
export const guides: Guide[] = [
  { file: 'README.md', title: 'Overview', summary: 'What the guides cover, and the examples to read' },
  { file: 'getting-started.md', title: 'Getting started', summary: 'Install, first page, <script> tag use, server templates, and per-component imports' },
  { file: 'jsx-and-html.md', title: 'JSX, configs and HTML', summary: 'The three ways to write the same UI and how props map to attributes' },
  { file: 'building-apps.md', title: 'Building apps', summary: 'App shell, routing with data loaders, data grids, stores, dialogs and menus' },
  { file: 'editors.md', title: 'Editors', summary: 'The code editor with pluggable engines, unsaved changes and JSON checks; the schema-driven property grid' },
  { file: 'data.md', title: 'Data and logic', summary: 'Stores, models and validators, proxies and NX.ajax, view models and bindings, controllers, remembered state, formatting' },
  { file: 'chat.md', title: 'Chat', summary: 'A chat window for AI: streaming replies, safe Markdown, Stop, connecting a model through your server' },
  { file: 'forms.md', title: 'Forms', summary: 'Fields, validation, native and fetch submission, and forms that work before JavaScript' },
  { file: 'server-rendering.md', title: 'Server rendering', summary: 'SSR and SSG with Declarative Shadow DOM, hydration, route data, and Twig/Blade/Jinja' },
  { file: 'theming.md', title: 'Theming', summary: 'Design tokens, light and dark themes, and restyling a component' },
  { file: 'internationalization.md', title: 'Internationalization', summary: 'Choosing a language, built-in translations, adding strings, locale-aware formatting, and server rendering in a language' },
  { file: 'accessibility.md', title: 'Accessibility', summary: 'Keyboard and screen-reader behavior of every component' },
  { file: 'custom-components.md', title: 'Custom components', summary: 'Writing your own component in the house style' },
  { file: 'performance.md', title: 'Performance', summary: 'Measured grid render and scroll times from 1,000 to 1,000,000 rows (generated by pnpm bench)' },
  { file: 'components.md', title: 'Component reference', summary: 'Every tag with its attributes, values and events (generated from the source)' }
];

const name = 'nx.js';
const blurb =
  'Accessible, themeable UI components as standard custom elements (`<nx-*>`, shadow DOM), with no runtime dependencies. ' +
  'Write them as JSX, as plain HTML (including from Twig, Blade and Jinja templates) or as `{ xtype }` config objects; ' +
  'they render on the server with Declarative Shadow DOM and upgrade in the browser.';

export function buildLlms(root: string, siteUrl: string): { index: string; full: string } {
  const base = siteUrl.replace(/\/+$/, '');
  const read = (file: string) => readFileSync(path.join(root, 'docs', file), 'utf8');

  const index = [
    `# ${name}`,
    '',
    `> ${blurb}`,
    '',
    'Components are JSX that creates real DOM (no React, no virtual DOM). Each guide below is plain Markdown; `llms-full.txt` has all of them in one file.',
    '',
    '## Docs',
    '',
    ...guides.map(g => `- [${g.title}](${base}/docs/${g.file}): ${g.summary}`),
    '',
    '## Optional',
    '',
    `- [Everything in one file](${base}/llms-full.txt): all of the docs above, for loading into a context window`,
    `- [Source and issues](https://github.com/usefuulness/nx.js): the repository`,
    ''
  ].join('\n');

  const full = [
    `# ${name}: full documentation`,
    '',
    `> ${blurb}`,
    '',
    ...guides.flatMap(g => [`\n---\n\n<!-- docs/${g.file} -->\n`, read(g.file).trim(), ''])
  ].join('\n');

  return { index, full: full.trimEnd() + '\n' };
}
