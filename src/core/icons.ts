const custom = new Map<string, string>();

function wrap(inner: string): string {
  return `<svg viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

export const Icons = {
  /**
   * Resolve an icon to markup. Accepts a registered name or raw SVG/HTML.
   * Returns '' for unknown names so a typo never breaks layout.
   */
  get(icon?: string | null): string {
    if (!icon) return '';
    const name = String(icon).trim();
    if (name.startsWith('<')) return name;
    if (custom.has(name)) return custom.get(name)!;
    if (paths[name]) return wrap(paths[name]);
    return '';
  },

  /** True if `name` resolves to an icon. */
  has(name: string): boolean {
    return custom.has(name) || name in paths;
  },

  /**
   * Register an icon. Pass either a full `<svg>` or just the inner
   * `<path>` markup for a 24x24 stroke icon.
   */
  register(name: string, svg: string): void {
    custom.set(name, svg.trim().startsWith('<svg') ? svg : wrap(svg));
  },

  /** All available icon names. */
  names(): string[] {
    return [...new Set([...Object.keys(paths), ...custom.keys()])].sort();
  },
};

export const icon = Icons.get;
